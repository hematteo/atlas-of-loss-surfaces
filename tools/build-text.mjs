// Builds js/text.js, which the page loads, from the Markdown in text/ (the format is described in text/README.md).
//   npm run text               build once
//   npm run text -- --watch    rebuild on every save
//   npm run text -- --check    fail if js/text.js is out of date (npm test runs this)
import { readFileSync, writeFileSync, readdirSync, statSync, watch } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const DIR = join(ROOT, 'text'), OUT = join(ROOT, 'js', 'text.js');
const HEADER = '// Generated by tools/build-text.mjs from the Markdown in text/. Do not edit this file: edit text/ and run `npm run text`.\n';

// headings of a plate file → [field, kind]. The order is the order of the plate card.
const SECTIONS = {
  'Subtitle': ['deck', 'inline'],
  'Lead': ['lead', 'blocks'],
  'In practice': ['take', 'blocks'],
  'Figure caption': ['cap', 'inline'],
  'Try': ['try', 'blocks'],
  'Background': ['bg', 'blocks'],
  'Method': ['method', 'blocks'],
  'Caveat': ['caveat', 'blocks'],
  'References': ['refs', 'refs'],
};
const REQUIRED = ['Subtitle', 'Lead', 'Try', 'Method', 'References'];
// _shared.md in a chapter folder: text shared by the proving-ground plates
const SHARED = { 'Method': ['pgHow', 'blocks'], 'Figure caption: race': ['race', 'inline'], 'Figure caption: arrivals': ['arrivals', 'inline'] };

class TextError extends Error {}
const fail = (file, line, msg) => { throw new TextError(`${relative(ROOT, file)}${line ? ':' + line : ''}: ${msg}`); };

// a file as numbered lines, with <!-- notes --> blanked out
function lines(file) {
  const src = readFileSync(file, 'utf8').replace(/<!--[\s\S]*?-->/g, (c) => c.replace(/[^\n]/g, ''));
  return src.split('\n').map((s, i) => ({ s: s.replace(/\s+$/, ''), n: i + 1 }));
}
// split at '# ' / '## ' headings: [{ title, n, body: lines }]
function sections(ls, level, file) {
  const mark = '#'.repeat(level) + ' ', out = [];
  for (const l of ls) {
    if (l.s.startsWith(mark)) out.push({ title: l.s.slice(mark.length).trim(), n: l.n, body: [] });
    else if (out.length) out[out.length - 1].body.push(l);
    else if (l.s) fail(file, l.n, `text before the first '${mark.trim()}' heading`);
  }
  return out;
}

// `code` becomes <code>, with < > & escaped. Everything else, HTML and [[glossary|links]] included, passes through.
const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
function inline(s, file, n) {
  if ((s.match(/`/g) || []).length % 2) fail(file, n, 'unmatched backtick');
  return s.replace(/`([^`]+)`/g, (_, c) => `<code>${esc(c)}</code>`);
}
// one paragraph; its lines are joined with a space
function inlineText(body, file, n) {
  const ls = body.filter((l) => l.s.trim());
  if (!ls.length) fail(file, n, 'empty section');
  const first = body.findIndex((l) => l.s.trim()), last = body.findLastIndex((l) => l.s.trim());
  const gap = body.slice(first, last + 1).find((l) => !l.s.trim());
  if (gap) fail(file, gap.n, 'this section is a single paragraph: remove the blank line');
  return inline(ls.map((l) => l.s.trim()).join(' '), file, ls[0].n);
}
// paragraphs separated by blank lines, numbered lists ('1. '), and, where allowed, '## ' subheadings (as <h4>).
// The lines of a paragraph or list item are joined with a space, so one sentence per line is fine.
function blocks(body, file, n, headings = false) {
  let html = '', i = 0;
  const join = (ls) => inline(ls.map((l) => l.s.trim()).join(' '), file, ls[0].n);
  while (i < body.length) {
    const l = body[i];
    if (!l.s.trim()) { i++; continue; }
    if (/^\d+\.\s/.test(l.s)) {
      const items = [];
      for (; i < body.length && body[i].s.trim(); i++) {
        if (/^\d+\.\s/.test(body[i].s)) items.push([{ s: body[i].s.replace(/^\d+\.\s+/, ''), n: body[i].n }]);
        else items[items.length - 1].push(body[i]);
      }
      html += '<ol>' + items.map((it) => `<li>${join(it)}</li>`).join('') + '</ol>';
    } else if (/^#+ /.test(l.s)) {
      if (!headings || !l.s.startsWith('## ')) fail(file, l.n, `unexpected heading '${l.s}'`);
      html += `<h4>${inline(l.s.slice(3).trim(), file, l.n)}</h4>`; i++;
    } else if (/^[-*+] /.test(l.s)) {
      fail(file, l.n, 'bulleted lists are not supported here: use a numbered list or <ul><li>…</li></ul>');
    } else {
      const p = [];
      for (; i < body.length && body[i].s.trim() && !/^\d+\.\s/.test(body[i].s); i++) p.push(body[i]);
      html += `<p>${join(p)}</p>`;
    }
  }
  if (!html) fail(file, n, 'empty section');
  return html;
}
// '- citation' then the note, indented, on the next line(s)
function refs(body, file, n) {
  const out = [];
  for (const l of body) {
    if (!l.s.trim()) continue;
    if (l.s.startsWith('- ')) out.push({ cite: l.s.slice(2).trim(), note: [], n: l.n });
    else if (/^\s/.test(l.s) && out.length) out[out.length - 1].note.push(l.s.trim());
    else fail(file, l.n, "each reference is '- citation', with its note indented on the next line");
  }
  if (!out.length) fail(file, n, 'no references');
  return out.map((r) => {
    if (!r.note.length) fail(file, r.n, 'this reference has no note: add one on the next line, indented');
    return [inline(r.cite, file, r.n), inline(r.note.join(' '), file, r.n)];
  });
}
const KIND = { inline: inlineText, blocks, refs };

function readSections(file, table, ls) {
  const out = {}, seen = new Set();
  for (const sec of sections(ls, 2, file)) {
    const spec = table[sec.title];
    if (!spec) fail(file, sec.n, `unknown section '## ${sec.title}'. The sections are: ${Object.keys(table).join(', ')}`);
    if (seen.has(sec.title)) fail(file, sec.n, `'## ${sec.title}' appears twice`);
    seen.add(sec.title);
    out[spec[0]] = KIND[spec[1]](sec.body, file, sec.n);
  }
  return [out, seen];
}

function plateFile(file) {
  const top = sections(lines(file), 1, file);
  if (top.length !== 1) fail(file, top[1]?.n, "a plate file has one '# Title' heading, at the top");
  const [p, seen] = readSections(file, SECTIONS, top[0].body);
  const missing = REQUIRED.filter((s) => !seen.has(s));
  if (missing.length) fail(file, 0, `missing section(s): ${missing.map((s) => '## ' + s).join(', ')}`);
  // keep the plate card's order of fields
  return { title: inline(top[0].title, file, top[0].n), ...Object.fromEntries(Object.values(SECTIONS).map(([k]) => [k, p[k]]).filter(([, v]) => v !== undefined)) };
}

function build() {
  const T = { chapters: [], chapterOf: {}, plates: {}, gloss: {}, about: '' };
  const chf = join(DIR, 'chapters.md');
  for (const l of lines(chf)) {
    const m = l.s.match(/^(\d+)\. (.+)$/);
    if (m) T.chapters[+m[1] - 1] = m[2].trim();
    else if (l.s.trim() && !l.s.startsWith('#')) fail(chf, l.n, "each chapter is a numbered line, '1. Landforms'");
  }
  for (const d of readdirSync(DIR).sort()) {
    const dir = join(DIR, d);
    if (!statSync(dir).isDirectory()) continue;
    const m = d.match(/^(\d+)-/);
    if (!m || !T.chapters[+m[1] - 1]) fail(dir, 0, `a chapter folder is named '<number>-<name>', with its number in text/chapters.md`);
    const ch = +m[1] - 1;
    for (const f of readdirSync(dir).sort()) {
      const file = join(dir, f);
      if (!f.endsWith('.md') || f === 'README.md') continue;
      if (f === '_shared.md') {
        const [s] = readSections(file, SHARED, lines(file).filter((l) => !l.s.startsWith('# ')));
        T.pgHow = s.pgHow; T.pgCap = { arrivals: s.arrivals, race: s.race };
        continue;
      }
      const id = f.slice(0, -3);
      if (!/^[a-z0-9]+$/.test(id)) fail(file, 0, 'a plate file is named after its plate id: lower-case letters and digits, then .md');
      T.plates[id] = plateFile(file);
      T.chapterOf[id] = ch;
    }
  }
  const gf = join(DIR, 'glossary.md');
  for (const sec of sections(lines(gf).filter((l) => !l.s.startsWith('# ')), 2, gf)) {
    const m = sec.title.match(/^([\w-]+): (.+)$/);
    if (!m) fail(gf, sec.n, "each entry is headed '## key: Term'");
    if (T.gloss[m[1]]) fail(gf, sec.n, `the key '${m[1]}' appears twice`);
    T.gloss[m[1]] = [inline(m[2].trim(), gf, sec.n), inlineText(sec.body, gf, sec.n)];
  }
  const af = join(DIR, 'about.md');
  T.about = blocks(lines(af).filter((l) => !l.s.startsWith('# ')), af, 0, true);
  return HEADER + 'const TEXT = ' + JSON.stringify(T, null, 2) + ';\n';
}

function run(mode) {
  try {
    const js = build();
    let old = null; try { old = readFileSync(OUT, 'utf8'); } catch { /* first build */ }
    if (mode === 'check') {
      if (js !== old) { console.error('js/text.js is out of date with text/: run `npm run text`'); return false; }
      console.log('js/text.js is up to date');
    } else if (js !== old) { writeFileSync(OUT, js); console.log(`built js/text.js (${new Date().toLocaleTimeString()})`); }
    return true;
  } catch (e) {
    if (!(e instanceof TextError)) throw e;
    console.error('text error: ' + e.message);
    return false;
  }
}

const mode = process.argv.includes('--check') ? 'check' : process.argv.includes('--watch') ? 'watch' : 'build';
const ok = run(mode);
if (mode === 'watch') {
  let t = 0;
  watch(DIR, { recursive: true }, () => { clearTimeout(t); t = setTimeout(() => run('build'), 100); });
  console.log('watching text/ (ctrl-c to stop)');
} else if (!ok) process.exit(1);
